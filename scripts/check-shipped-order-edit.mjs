import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

// Run the component's real permission methods without bootstrapping Angular.
const source = ts.createSourceFile('component.ts', readFileSync(new URL('../src/app/app.component.ts', import.meta.url), 'utf8'), ts.ScriptTarget.Latest, true);
const component = source.statements.find(n => ts.isClassDeclaration(n) && n.name.text === 'AppComponent');
const names = ['canEditOrder', 'canEditOrderPrice', 'isOrderItemEditable', 'startOrderEdit', 'cancelOrderEdit', 'setOrderDraftItems', 'updateOrderItemQty', 'updateOrderItemPrice', 'removeOrderItem', 'saveOrderEdit', 'updateOrderItemDiscount'];
const methods = component.members.filter(n => names.includes(n.name?.getText(source))).map(n => n.getText(source)).join('\n');
const js = ts.transpileModule(`export class Permissions { ${methods} }`, { compilerOptions: { module: ts.ModuleKind.ES2022 } }).outputText;
const { Permissions } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const permissions = new Permissions();
let role = 'manager';
permissions.role = () => role;
permissions.selectedDistributorId = () => 10;
const order = { distributorId: 10, status: 'shipped' };
assert.equal(permissions.canEditOrder(order), true, 'manager can edit shipped orders');
assert.equal(permissions.canEditOrderPrice(order), true, 'manager can change shipped order prices');
role = 'admin';
assert.equal(permissions.canEditOrder(order), true);
assert.equal(permissions.canEditOrderPrice(order), true);
role = 'distributor';
assert.equal(permissions.canEditOrder(order), false);
assert.equal(permissions.canEditOrderPrice(order), false);
assert.equal(permissions.canEditOrder({ ...order, status: 'pending' }), true);
assert.equal(permissions.canEditOrderPrice({ ...order, status: 'pending' }), false);
assert.equal(permissions.canEditOrder({ ...order, distributorId: 11, status: 'pending' }), false);
role = 'manager';
assert.equal(permissions.canEditOrder({ ...order, status: 'delivered' }), false);
assert.equal(permissions.canEditOrderPrice({ ...order, status: 'cancelled' }), false);
console.log('Shipped order permissions: 11 assertions passed');

function state(value) { const s = () => value; s.set = next => value = next; return s; }
permissions.orderEditDraft = state(null);
permissions.orderEditSaving = state(false);
permissions.orderEditError = state('');
permissions.addItemModal = state(false);
const shipped = { ...order, id: 'order-1', uuid: 'uuid-1', amount: 200, items: [{ productId: 1, qty: 2, unitPrice: 100, amount: 200 }] };
permissions.selectedOrder = () => permissions.orderEditDraft() ?? shipped;
assert.equal(permissions.isOrderItemEditable(shipped), false, 'shipped order starts read-only');
permissions.startOrderEdit();
assert.equal(permissions.isOrderItemEditable(shipped), true);
permissions.setOrderDraftItems([{ ...shipped.items[0], qty: 3, unitPrice: 120 }]);
assert.equal(permissions.orderEditDraft().amount, 360);
assert.equal(permissions.orderEditDraft().items[0].amount, 360);
assert.equal(shipped.items[0].qty, 2, 'editing leaves saved order intact');
permissions.cancelOrderEdit();
assert.equal(permissions.orderEditDraft(), null);
assert.equal(permissions.isOrderItemEditable(shipped), false);
role = 'distributor';
permissions.startOrderEdit();
assert.equal(permissions.orderEditDraft(), null, 'distributor cannot start shipped editing');
console.log('Shipped order edit/cancel: 8 assertions passed');

role = 'manager';
permissions.orders = () => [shipped];
permissions.reloadAll = async () => {};
let writes = 0;
permissions.orderService = { saveShippedItems: async (id, items) => {
  assert.equal(id, 'uuid-1');
  assert.equal(items[0].qty, 4);
  assert.equal(items[0].unitPrice, 125.56);
  writes++;
  return null;
} };
permissions.startOrderEdit();
await permissions.updateOrderItemQty(shipped.id, 1, 4);
await permissions.updateOrderItemPrice(shipped.id, 1, 125.555);
assert.equal(permissions.orderEditDraft().amount, 502.24);
assert.equal(writes, 0, 'draft changes do not write to the backend');
assert.equal(shipped.amount, 200);
await permissions.saveOrderEdit();
assert.equal(writes, 1);
assert.equal(permissions.orderEditDraft(), null);
assert.equal(permissions.orderEditSaving(), false);
permissions.startOrderEdit();
permissions.setOrderDraftItems([...shipped.items, { productId: 2, qty: 1, unitPrice: 50, amount: 50 }]);
await permissions.updateOrderItemQty(shipped.id, 2, 3);
assert.equal(permissions.orderEditDraft().amount, 350, 'new unsaved books remain editable');
await permissions.removeOrderItem(shipped.id, 2);
assert.equal(permissions.orderEditDraft().items.length, 1);
permissions.orderService.saveShippedItems = async () => 'database unavailable';
await permissions.saveOrderEdit();
assert.notEqual(permissions.orderEditDraft(), null, 'failure preserves edits');
assert.match(permissions.orderEditError(), /database unavailable/);
assert.equal(permissions.orderEditSaving(), false);
permissions.cancelOrderEdit();
assert.equal(permissions.orderEditError(), '');
console.log('Shipped order save/error and draft mutations: passed');

permissions.startOrderEdit();
permissions.orderBaseUnitPrice = () => 300;
permissions.setOrderDraftItems([{ ...shipped.items[0], unitPrice: 174, discount: .42, qty: 10 }]);
assert.equal(typeof permissions.updateOrderItemDiscount, 'function', 'discount editing must be available');
await permissions.updateOrderItemDiscount(shipped.id, 1, 50);
assert.equal(permissions.orderEditDraft().items[0].discount, .5);
assert.equal(permissions.orderEditDraft().items[0].unitPrice, 150);
assert.equal(permissions.orderEditDraft().amount, 1500);
await permissions.updateOrderItemDiscount(shipped.id, 1, 100);
assert.equal(permissions.orderEditDraft().amount, 0);
await permissions.updateOrderItemDiscount(shipped.id, 1, 0);
assert.equal(permissions.orderEditDraft().amount, 3000);
for (const invalid of [-1, 101, NaN]) {
  await permissions.updateOrderItemDiscount(shipped.id, 1, invalid);
  assert.equal(permissions.orderEditDraft().amount, 3000);
}
role = 'distributor';
await permissions.updateOrderItemDiscount(shipped.id, 1, 50);
assert.equal(permissions.orderEditDraft().amount, 3000);
role = 'manager';
permissions.cancelOrderEdit();
assert.equal(shipped.amount, 200);
console.log('Discount editing: recalculation, boundaries, permissions and cancel passed');
