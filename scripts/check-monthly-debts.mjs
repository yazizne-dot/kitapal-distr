import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const exports = {};
let calls = [];
let resolveFirst;
let serverError = null;
const signal = value => { const f = () => value; f.set = next => value = next; return f; };
const supabase = {rpc: async (_name, args) => {
  calls.push(args.requested_month);
  if (calls.length === 1) return new Promise(resolve => resolveFirst = resolve);
  if (serverError) return {data: null, error: serverError};
  return {data: [{distributor_id: 1, opening_debt: '1000', paid: '200', debt: '1100', credit_limit: '3000'}], error: null};
}};
const source = readFileSync('src/app/core/services/monthly-debt.service.ts', 'utf8');
const code = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, experimentalDecorators: true}}).outputText;
new Function('require', 'exports', code)(name => name === '@angular/core' ? {Injectable: () => c => c, signal} : {supabase}, exports);
const service = new exports.MonthlyDebtService();
const first = service.load('2026-09');
await service.load('2026-10');
assert.equal(service.rows()[0].paid, 200);
assert.equal(service.rows()[0].debt, 1100);
resolveFirst({data: [{distributor_id: 1, debt: 999}], error: null});
await first;
assert.equal(service.rows()[0].debt, 1100, 'a slow earlier month must not replace the selected month');
assert.deepEqual(calls, ['2026-09-01', '2026-10-01']);
serverError = {message: 'Missing RPC'};
await service.load('2026-08');
assert.deepEqual(service.rows(), [], 'failed months must not display amounts from another month');
assert.ok(service.error());
assert.equal(service.loading(), false);
serverError = null;
await service.load('2026-10');
assert.equal(service.error(), '', 'retry must clear the error');
assert.equal(service.rows()[0].opening_debt, 1000);
console.log('Monthly debt: date bounds, numeric amounts and stale response protection passed');
