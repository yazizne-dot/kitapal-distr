import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const source=readFileSync('src/app/app.component.ts','utf8');
const method=source.slice(source.indexOf('  refreshCalendarMonth():'),source.indexOf('  private applyAuthState'));
const code=ts.transpileModule(`class Calendar {${method}}`,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
let month='2026-11';
const Calendar=new Function('orderMonthKey',code+';return Calendar;')(()=>month);
const signal=value=>{const f=()=>value;f.set=next=>value=next;return f;};
const c=new Calendar();c.debtCurrentMonth='2026-10';c.CURRENT_MONTH='2026-10';
c.debtMonth=signal('2026-10');c.distributorOrderMonth=signal('2026-10');c.editingOpeningDebtId=signal(1);
c.signedIn=()=>true;c.activeScreen=()=> 'debts';
let loads=[];c.monthlyDebtService={load:async m=>loads.push(m)};
c.refreshCalendarMonth();assert.equal(c.debtMonth(),'2026-11');assert.equal(c.CURRENT_MONTH,'2026-11');
assert.equal(c.distributorOrderMonth(),'2026-11');assert.equal(c.editingOpeningDebtId(),null);
assert.deepEqual(loads,['2026-11']);
c.debtMonth.set('2026-08');c.distributorOrderMonth.set('all');month='2026-12';
c.refreshCalendarMonth();assert.equal(c.debtMonth(),'2026-08','selected history month must remain selected');
assert.equal(c.distributorOrderMonth(),'all');
c.refreshCalendarMonth();assert.equal(loads.length,2,'unchanged month must not reload');
console.log('Calendar rollover: active month advances, history remains selected and stale opening editor closes');
